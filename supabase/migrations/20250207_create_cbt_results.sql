CREATE POLICY "Users can insert own CBT results" ON public.cbt_results
    FOR INSERT WITH CHECK (auth.uid() = student_id);

-- Allow teachers to update/delete results
CREATE POLICY "Enable insert for authenticated users only" ON public.cbt_results FOR INSERT WITH CHECK (auth.role() = 'authenticated');
