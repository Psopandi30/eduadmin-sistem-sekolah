-- Create table for storing CBT results
-- This table stores the final score and details of students' CBT sessions
-- It links to student profiles and potentially specific exam/sessions

CREATE TABLE public.cbt_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id UUID REFERENCES auth.users(id) ON DELETE CASCADE, -- Optional: Link to auth user if applicable
    student_name TEXT NOT NULL, -- Fallback if not using auth linking
    student_class TEXT,
    exam_title TEXT NOT NULL,
    exam_type TEXT NOT NULL, -- e.g., 'Tryout', 'Latihan', 'Ujian'
    score NUMERIC NOT NULL,
    total_score NUMERIC NOT NULL,
    status TEXT, -- e.g., 'Lulus', 'Kompeten', 'Cukup'
    submitted_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    details JSONB -- Store detailed answers or other metadata
);

-- RLS Policies
ALTER TABLE public.cbt_results ENABLE ROW LEVEL SECURITY;

-- Allow authenticated users to view their own results
CREATE POLICY "Users can view own CBT results" ON public.cbt_results
    FOR SELECT USING (auth.uid() = student_id);

